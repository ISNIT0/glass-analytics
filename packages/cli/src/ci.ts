/**
 * Upgrades through CI. After `dataflare init`, the deployment is pinned by
 * `.glass/config.json` → `version`, and a GitHub Actions workflow deploys
 * exactly that version whenever `.glass/` changes on the default branch.
 *
 * Upgrading is then a normal code change:
 *   1. `npx dataflare@latest upgrade` on a laptop stages the new
 *      Worker, migrations and version into `.glass/` (no deploy).
 *   2. Commit and push (or open a PR). The workflow migrates and deploys.
 *
 * That keeps the live Worker matching the repo, and keeps Cloudflare tokens
 * in CI secrets rather than on whichever machine last ran `dataflare upgrade`.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

export const CI_WORKFLOW_PATH = '.github/workflows/glass.yml';
export const CI_SECRET = 'CLOUDFLARE_API_TOKEN';
const MARKER = '# Generated by `dataflare ci`.';
/** The marker before the rename from Glass: those workflows are ours too, and get rewritten. */
const OLD_MARKER = '# Generated by `glass ci`.';

export interface CiOptions {
  /** Branch whose pushes deploy. Defaults to the repo's default branch, else main. */
  branch?: string;
  /** Repository secret holding the Cloudflare API token. */
  secret?: string;
}

/** True inside a CI runner (GitHub Actions and most others set CI=true). */
export function inCi(env: NodeJS.ProcessEnv = process.env): boolean {
  return env.CI === 'true' || env.CI === '1' || env.GITHUB_ACTIONS === 'true';
}

export function hasCiWorkflow(root: string): boolean {
  return existsSync(join(root, CI_WORKFLOW_PATH));
}

/** The repo's default branch from origin/HEAD, else the current branch, else "main". */
export function defaultBranch(root: string): string {
  const git = (args: string[]) => {
    try {
      return execFileSync('git', args, {
        cwd: root,
        encoding: 'utf8',
        stdio: ['ignore', 'pipe', 'ignore'],
      }).trim();
    } catch {
      return '';
    }
  };
  const head = git(['symbolic-ref', '--short', 'refs/remotes/origin/HEAD']).replace(
    /^origin\//,
    '',
  );
  return head || git(['branch', '--show-current']) || 'main';
}

export function ciWorkflow(o: Required<CiOptions>): string {
  return `${MARKER} Deploys the Dataflare analytics Worker from .glass/.
#
# The version is pinned in .glass/config.json. To upgrade:
#   npx dataflare@latest upgrade   # stages the new Worker into .glass/
#   git commit .glass && git push            # this workflow migrates and deploys it
#
# Needs repository secret ${o.secret}: a Cloudflare API token with
# Workers Scripts Edit, D1 Edit, Workers R2 Storage Edit, Account Settings Read
# (and Zone Workers Routes Edit if .glass/config.json has a route).
# Worker secrets (API keys) are set by \`dataflare init\` and survive deploys.
name: Dataflare

on:
  push:
    branches: [${o.branch}]
    paths: ['.glass/**', '${CI_WORKFLOW_PATH}']
  workflow_dispatch:

concurrency:
  group: glass-deploy
  cancel-in-progress: false

jobs:
  deploy:
    runs-on: ubuntu-latest
    permissions:
      contents: read
    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: Deploy the Dataflare version pinned in .glass/config.json
        run: |
          version="$(node -p "require('./.glass/config.json').version")"
          npx -y "dataflare@\${version}" upgrade --ci
        env:
          CLOUDFLARE_API_TOKEN: \${{ secrets.${o.secret} }}
`;
}

/**
 * Write the workflow. Leaves a hand-edited workflow alone (one without the
 * generated marker) and reports it as kept. Returns what happened.
 */
export function writeCiWorkflow(
  root: string,
  options: CiOptions = {},
): { path: string; status: 'created' | 'updated' | 'kept'; branch: string; secret: string } {
  const branch = options.branch ?? defaultBranch(root);
  const secret = options.secret ?? CI_SECRET;
  const path = join(root, CI_WORKFLOW_PATH);
  const next = ciWorkflow({ branch, secret });
  if (existsSync(path)) {
    const current = readFileSync(path, 'utf8');
    if (!current.startsWith(MARKER) && !current.startsWith(OLD_MARKER))
      return { path: CI_WORKFLOW_PATH, status: 'kept', branch, secret };
    if (current === next) return { path: CI_WORKFLOW_PATH, status: 'kept', branch, secret };
    writeFileSync(path, next);
    return { path: CI_WORKFLOW_PATH, status: 'updated', branch, secret };
  }
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, next);
  return { path: CI_WORKFLOW_PATH, status: 'created', branch, secret };
}

/** What a human or agent must do after the workflow is written. Shown by `dataflare init` and `dataflare ci`. */
export function ciNextSteps(o: { branch: string; secret: string }): string[] {
  return [
    `Add repository secret ${o.secret} (a Cloudflare API token; same scopes as init): gh secret set ${o.secret}`,
    `Commit .glass/ (not credentials.json, which is git-ignored) and ${CI_WORKFLOW_PATH}, then push to ${o.branch}.`,
    'Upgrade later with `npx dataflare@latest upgrade`: it stages the new version into .glass/ without deploying. Commit and push; the workflow deploys it.',
    'Do not deploy Dataflare from a laptop once this workflow exists. `dataflare upgrade --local` overrides that for emergencies only.',
  ];
}
